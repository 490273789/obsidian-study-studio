#!/usr/bin/env node
import { execFileSync, spawnSync } from "node:child_process";
import fs from "node:fs";
import path from "node:path";

const gitDir = path.resolve(process.cwd(), ".git");

if (!fs.existsSync(gitDir)) {
	console.log("\x1b[33m[WARN]\x1b[0m 未检测到 .git 目录，跳过 Git hooks 安装。");
	process.exit(0);
}

const configuredPath = spawnSync("git", ["config", "--get", "core.hooksPath"]);
if (configuredPath.status === 0) {
	console.log("已配置 core.hooksPath，沿用现有 Git hooks。");
	process.exit(0);
}
if (configuredPath.status !== 1) throw configuredPath.error ?? new Error("无法读取 Git 配置");

const hooksDir = execFileSync(
	"git",
	["rev-parse", "--path-format=absolute", "--git-path", "hooks"],
	{
		encoding: "utf8",
	},
).trimEnd();
fs.mkdirSync(hooksDir, { recursive: true });

function installHook(name, content) {
	const destination = path.join(hooksDir, name);
	try {
		fs.writeFileSync(destination, content, { flag: "wx", mode: 0o755 });
		console.log(`已安装 ${name} hook`);
	} catch (error) {
		if (error.code !== "EEXIST") throw error;
		console.log(`保留已有的 ${name} hook`);
	}
}

// 1. commit-msg hook
const commitMsgHookContent = `#!/bin/sh
# Auto-generated by scripts/setup-hooks.mjs
node scripts/verify-commit-msg.mjs "$1"
`;

installHook("commit-msg", commitMsgHookContent);

// 2. pre-commit hook
const preCommitHookContent = `#!/bin/sh
# Auto-generated by scripts/setup-hooks.mjs

echo "\x1b[36m🔍 运行提交前代码检查 (format & lint)...\x1b[0m"

# Vite Plus 格式、Lint、类型检查，并保留独立 tsc 校验
pnpm run check && pnpm run typecheck
if [ $? -ne 0 ]; then
  echo "\n\x1b[31m❌ 代码检查未通过！请运行 'pnpm run format' 或修复 Lint / 类型错误后重试。\x1b[0m\n"
  exit 1
fi

echo "\x1b[32m✔ 提交前代码质量检查通过\x1b[0m"
`;

installHook("pre-commit", preCommitHookContent);
